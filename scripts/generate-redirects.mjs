// 生成旧（中文）URL → 新（英文 key）URL 的 301 跳转表。
// 解析 data/categories.ts 与 data/tags.ts 的注册表（正则提取，避免引入 TS 加载器），
// 再扫描 data/blog 下的文章 frontmatter 拿到 key。输出 lib/redirects.generated.cjs。
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'fs'
import path from 'path'
import { slug } from 'github-slugger'

const root = process.cwd()

// 从 "key: { name: '...' }" 形式提取 key -> name
function parseRegistry(fileRel) {
  const text = readFileSync(path.join(root, fileRel), 'utf8')
  const map = {}
  const re = /(\w[\w-]*)\s*:\s*\{\s*name\s*:\s*'([^']*)'/g
  let m
  while ((m = re.exec(text))) {
    map[m[1]] = m[2]
  }
  return map
}

const catKeyToName = parseRegistry('data/categories.ts')
const tagKeyToName = parseRegistry('data/tags.ts')

const redirects = []

// 分类：/categories/<中文名> -> /categories/<key>
for (const [key, name] of Object.entries(catKeyToName)) {
  if (key !== name) {
    redirects.push({
      source: encodeURI(`/categories/${name}`),
      destination: `/categories/${key}`,
      permanent: true,
    })
  }
}

// 标签：/tags/<slug(中文)> -> /tags/<key>
for (const [key, name] of Object.entries(tagKeyToName)) {
  const old = slug(name)
  if (old !== key) {
    redirects.push({
      source: encodeURI(`/tags/${old}`),
      destination: `/tags/${key}`,
      permanent: true,
    })
  }
}

// 文章：/blog/<中文分类>/<中文文件名> -> /blog/<分类key>/<文章key>
function walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry)
    const st = statSync(full)
    if (st.isDirectory()) {
      walk(full)
    } else if (/\.(md|mdx)$/.test(entry)) {
      const newCat = path.basename(dir) // 文件夹已是英文 key
      const oldCat = catKeyToName[newCat] ?? newCat
      const oldFile = entry.replace(/\.(md|mdx)$/, '')
      const raw = readFileSync(full, 'utf8')
      const km = raw.match(/^key:\s*'([^']*)'/m)
      if (!km) continue
      const postKey = km[1]
      redirects.push({
        source: encodeURI(`/blog/${oldCat}/${oldFile}`),
        destination: `/blog/${newCat}/${postKey}`,
        permanent: true,
      })
    }
  }
}
walk(path.join(root, 'data/blog'))

mkdirSync(path.join(root, 'lib'), { recursive: true })
const out = `// AUTO-GENERATED by scripts/generate-redirects.mjs — 不要手动编辑。
// 旧（中文）URL -> 新（英文 key）URL 的 301 跳转。
module.exports = ${JSON.stringify(redirects, null, 2)}
`
writeFileSync(path.join(root, 'lib/redirects.generated.cjs'), out)
console.log(`Generated ${redirects.length} redirects -> lib/redirects.generated.cjs`)
